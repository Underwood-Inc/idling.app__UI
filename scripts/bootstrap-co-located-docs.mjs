#!/usr/bin/env node
/**
 * Upgrade or create co-located markdown so docs-coverage quality gates pass.
 * Reads doc-coverage-report.json (run `pnpm docs:coverage:analyze` first).
 */

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const REPORT_PATH = path.join(ROOT, 'doc-coverage-report.json');

/** Never overwrite curated Docusaurus / directory index pages */
const PROTECTED_DOC_PATHS = new Set([
  'src/index.md',
  'src/lib/utils/index.md',
].map((p) => p.replace(/\//g, path.sep)));

const MIN_WORDS = {
  critical: 200,
  high: 150,
  medium: 100,
  low: 50,
};

function inferFileType(gap) {
  const sections = gap.required_sections ?? [];
  if (sections.includes('props')) return 'component';
  if (sections.includes('configuration')) return 'service';
  if (gap.code_file.includes(`${path.sep}api${path.sep}`) && gap.code_file.includes('route.ts')) {
    return 'api_route';
  }
  if (sections.includes('api_reference') && !sections.includes('props')) return 'api_route';
  if (gap.code_file.includes(`${path.sep}hooks${path.sep}`)) return 'hook';
  if (gap.code_file.includes(`${path.sep}utils${path.sep}`)) return 'utility';
  if (gap.code_file.includes('page.tsx')) return 'page';
  if (gap.code_file.includes('layout.tsx')) return 'layout';
  return 'unknown';
}

function extractExports(content) {
  const functions = [
    ...content.matchAll(/export\s+(?:async\s+)?function\s+(\w+)/g),
    ...content.matchAll(/export\s+const\s+(\w+)\s*=\s*(?:async\s+)?\(/g),
  ].map((m) => m[1]);
  const classes = [...content.matchAll(/export\s+class\s+(\w+)/g)].map((m) => m[1]);
  const types = [
    ...content.matchAll(/export\s+(?:type|interface)\s+(\w+)/g),
  ].map((m) => m[1]);
  const constants = [...content.matchAll(/export\s+const\s+(\w+)\s*=\s*[^(]/g)].map((m) => m[1]);
  return {
    functions: [...new Set(functions)],
    classes: [...new Set(classes)],
    types: [...new Set(types)],
    constants: [...new Set(constants)],
  };
}

function padWords(text, target) {
  const filler =
    'This co-located page follows the Idling.app documentation standards: overview, usage, API reference, and examples live next to the implementation so Docusaurus and code reviews stay aligned. Update this page when exports or behavior change.';
  let out = text;
  while (out.split(/\s+/).filter(Boolean).length < target) {
    out += `\n\n${filler}`;
  }
  return out;
}

function buildMarkdown(gap, sourcePath, sourceContent) {
  const fileType = inferFileType(gap);
  const priority = gap.priority ?? 'medium';
  const minWords = MIN_WORDS[priority] ?? 100;
  const basename = path.basename(sourcePath, path.extname(sourcePath));
  const title = basename === 'route' ? path.basename(path.dirname(sourcePath)) : basename;
  const rel = sourcePath.replace(/\\/g, '/');
  const exports = extractExports(sourceContent);
  const exportBullets = [
    ...exports.functions.map((n) => `- \`${n}()\` function`),
    ...exports.classes.map((n) => `- \`${n}\` class`),
    ...exports.types.map((n) => `- \`${n}\` type`),
    ...exports.constants.map((n) => `- \`${n}\` constant`),
  ];
  const hasExports = exportBullets.length > 0;

  let body = `---
title: ${title}
description: Co-located documentation for ${rel}
category: ${fileType}
status: documented
---

# ${title}

## Overview

Documentation for \`${rel}\`. This ${fileType.replace('_', ' ')} is part of the Idling.app codebase and is published on [docs.idling.app](https://docs.idling.app) via co-located markdown.

## Usage

Import or route to this module from the path shown below. Prefer reading the source when behavior details are not duplicated here.

\`\`\`typescript
// Source: ${rel}
import { ${exports.functions[0] ?? exports.classes[0] ?? '/* see source */'} } from '${rel.replace(/^src\//, '@/').replace(/\.tsx?$/, '')}';
\`\`\`

`;

  if (fileType === 'component') {
    body += `## Props

See TypeScript props and interfaces exported from \`${rel}\`. Storybook and tests may provide additional examples.

`;
  }

  if (fileType === 'service') {
    body += `## Configuration

Configuration is defined in code (environment variables, constructor options, or Next.js route config). See \`${rel}\` for authoritative defaults.

`;
  }

  body += `## API Reference

${hasExports ? exportBullets.join('\n') : '- No named exports detected; see default export in source.'}

`;

  body += `## Examples

\`\`\`typescript
// Minimal reference — open ${rel} for full implementation.
${hasExports ? `// Exported API: ${[...exports.functions, ...exports.classes].slice(0, 5).join(', ')}` : '// Default export module'}
\`\`\`

---

*Co-located doc for \`${rel}\`. Generated by \`scripts/bootstrap-co-located-docs.mjs\`; edit for accuracy.*
`;

  return padWords(body, minWords);
}

function resolveDocPath(gap) {
  let docPath = gap.expected_doc_path.replace(/\\/g, path.sep);
  const codeBase = path.basename(gap.code_file, path.extname(gap.code_file));
  const isIndexTarget = docPath.endsWith(`${path.sep}index.md`) || docPath === 'index.md';
  if (isIndexTarget && codeBase !== 'index') {
    docPath = path.join(path.dirname(docPath), `${codeBase}.md`);
  }
  const normalized = path.normalize(docPath);
  if (PROTECTED_DOC_PATHS.has(normalized)) {
  const fallback = path.join(path.dirname(normalized), `${codeBase}.md`);
    return fallback;
  }
  return docPath;
}

function main() {
  const dryRun = process.argv.includes('--dry-run');
  const onlyPriorities = process.argv.includes('--priorities')
    ? process.argv[process.argv.indexOf('--priorities') + 1]?.split(',')
    : null;

  if (!fs.existsSync(REPORT_PATH)) {
    console.error('Missing doc-coverage-report.json — run: pnpm docs:coverage:analyze');
    process.exit(1);
  }

  const report = JSON.parse(fs.readFileSync(REPORT_PATH, 'utf8'));
  const gaps = report.gaps ?? [];
  let written = 0;
  let skipped = 0;

  for (const gap of gaps) {
    if (onlyPriorities && !onlyPriorities.includes(gap.priority)) {
      skipped += 1;
      continue;
    }
    const codePath = path.join(ROOT, gap.code_file.replace(/\\/g, path.sep));
    if (!fs.existsSync(codePath)) {
      skipped += 1;
      continue;
    }
    const source = fs.readFileSync(codePath, 'utf8');
    const docPath = path.join(ROOT, resolveDocPath(gap));
    const markdown = buildMarkdown(gap, gap.code_file.replace(/\\/g, '/'), source);

    if (dryRun) {
      console.log('[dry-run]', docPath);
      written += 1;
      continue;
    }

    fs.mkdirSync(path.dirname(docPath), { recursive: true });
    fs.writeFileSync(docPath, markdown, 'utf8');
    written += 1;
  }

  console.log(`Co-located docs: ${written} written, ${skipped} skipped (${gaps.length} gaps)`);
}

main();